  <script>
  document.addEventListener("DOMContentLoaded", function() {
    const buttons = document.querySelectorAll(".accordion-button");

    buttons.forEach(button => {
      button.addEventListener("click", function() {
        const target = this.getAttribute("data-mdb-target");
        const collapseElement = document.querySelector(target);

        // Toggle the collapsed class and aria attributes
        if (collapseElement.classList.contains("show")) {
          collapseElement.classList.remove("show");
          this.setAttribute("aria-expanded", "false");
        } else {
          // Close all other open items
          document.querySelectorAll(".accordion-collapse.show").forEach(collapse => {
            collapse.classList.remove("show");
            const relatedButton = collapse.previousElementSibling.querySelector(".accordion-button");
            relatedButton.setAttribute("aria-expanded", "false");
          });

          // Open the current item
          collapseElement.classList.add("show");
          this.setAttribute("aria-expanded", "true");
        }
      });
    });
  });
</script>



